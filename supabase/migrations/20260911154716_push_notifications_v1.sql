create extension if not exists pg_net with schema extensions;
create extension if not exists pg_cron;

create table if not exists public.push_private_config (
  key text primary key,
  value text not null,
  updated_at timestamptz not null default now()
);
alter table public.push_private_config enable row level security;

create table if not exists public.push_subscriptions (
  id uuid primary key default gen_random_uuid(),
  profile_id text not null references public.profiles(id) on delete cascade,
  auth_user_id uuid,
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,
  user_agent text not null default '',
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.push_subscriptions enable row level security;
create index if not exists push_subscriptions_profile_idx on public.push_subscriptions(profile_id) where enabled;

create table if not exists public.notification_outbox (
  id bigint generated by default as identity primary key,
  event_type text not null,
  actor_profile_id text,
  target_profile_id text,
  title text not null default '여린교회',
  body text not null,
  data jsonb not null default '{}'::jsonb,
  dedupe_key text not null unique,
  not_before timestamptz not null default now(),
  created_at timestamptz not null default now(),
  sent_at timestamptz
);
alter table public.notification_outbox enable row level security;
create index if not exists notification_outbox_due_idx on public.notification_outbox(sent_at,not_before,id) where sent_at is null;

create or replace function public.yeorin_notify_new_qt() returns trigger language plpgsql security definer set search_path=public as $$
begin
  insert into public.notification_outbox(event_type,actor_profile_id,title,body,data,dedupe_key)
  values('qt_new',new.author_id,'여린교회','새로운 나눔이 등록됐어요',jsonb_build_object('tab','nanum','sub','qt','date',new.post_date::text,'postId',new.id),'qt_new:'||new.id)
  on conflict(dedupe_key) do nothing;
  return new;
end $$;
drop trigger if exists trg_yeorin_notify_new_qt on public.qt_posts;
create trigger trg_yeorin_notify_new_qt after insert on public.qt_posts for each row execute function public.yeorin_notify_new_qt();

