create or replace function public.yeorin_notification_target(p_type text,p_id text) returns jsonb language plpgsql stable security definer set search_path=public as $$
declare v_author text; v_data jsonb;
begin
  if p_type='community' then
    select author_id, jsonb_build_object('tab','community','postId',id::text) into v_author,v_data from public.community_posts where id::text=p_id;
  elsif p_type='qt' then
    select author_id, jsonb_build_object('tab','nanum','sub','qt','date',post_date::text,'postId',id) into v_author,v_data from public.qt_posts where id=p_id;
  elsif p_type='prayer' then
    select author_id, jsonb_build_object('tab','nanum','sub','prayer','date',post_date::text,'postId',id) into v_author,v_data from public.prayer_posts where id=p_id;
  else return null; end if;
  if v_author is null then return null; end if;
  return jsonb_build_object('authorId',v_author,'data',coalesce(v_data,'{}'::jsonb));
end $$;

create or replace function public.yeorin_notify_reaction() returns trigger language plpgsql security definer set search_path=public as $$
declare v_target jsonb; v_author text; v_actor_name text; v_data jsonb;
begin
  if new.reaction_key<>'heart' then return new; end if;
  v_target:=public.yeorin_notification_target(new.target_type,new.target_id);if v_target is null then return new; end if;
  v_author:=v_target->>'authorId';if v_author is null or v_author=new.user_id then return new; end if;
  select name into v_actor_name from public.profiles where id=new.user_id;v_data:=coalesce(v_target->'data','{}'::jsonb);
  insert into public.notification_outbox(event_type,actor_profile_id,target_profile_id,title,body,data,dedupe_key)
  values('reaction',new.user_id,v_author,'여린교회',coalesce(v_actor_name,'누군가')||'님이 내 글에 좋아요를 눌렀어요',v_data,'reaction:'||new.target_type||':'||new.target_id||':'||new.user_id||':'||new.reaction_key)
  on conflict(dedupe_key) do nothing;
  return new;
end $$;
drop trigger if exists trg_yeorin_notify_reaction on public.reactions;
create trigger trg_yeorin_notify_reaction after insert on public.reactions for each row execute function public.yeorin_notify_reaction();

