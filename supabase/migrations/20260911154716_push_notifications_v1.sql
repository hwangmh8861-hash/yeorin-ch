create or replace function public.yeorin_enqueue_calendar_notifications() returns void language plpgsql security definer set search_path=public as $$
declare v_now timestamp:=timezone('Asia/Seoul',now());v_today date:=timezone('Asia/Seoul',now())::date;v_tomorrow date:=timezone('Asia/Seoul',now())::date+1;r record;
begin
  if extract(hour from v_now)=9 then
    for r in select id,title,event_date from public.calendar_events where type='birthday' and to_char(event_date,'MM-DD')=to_char(v_today,'MM-DD') loop
      insert into public.notification_outbox(event_type,title,body,data,dedupe_key) values('birthday_today','여린교회','오늘은 '||r.title||'님 생일이에요 🎉',jsonb_build_object('tab','calendar','date',v_today::text),'birthday_today:'||v_today::text||':'||r.id) on conflict(dedupe_key) do nothing;
    end loop;
    for r in select id,title,event_date from public.calendar_events where type='birthday' and to_char(event_date,'MM-DD')=to_char(v_tomorrow,'MM-DD') loop
      insert into public.notification_outbox(event_type,title,body,data,dedupe_key) values('birthday_tomorrow','여린교회','내일은 '||r.title||'님 생일이에요 🎂',jsonb_build_object('tab','calendar','date',v_tomorrow::text),'birthday_tomorrow:'||v_today::text||':'||r.id) on conflict(dedupe_key) do nothing;
    end loop;
  end if;
  if extract(hour from v_now)=19 then
    for r in select id,title,event_date,start_time from public.calendar_events where type<>'birthday' and event_date=v_tomorrow loop
      insert into public.notification_outbox(event_type,title,body,data,dedupe_key) values('calendar_tomorrow','여린교회','내일 '||r.title||' 일정이 있어요'||case when coalesce(r.start_time,'')<>'' then ' · '||r.start_time else '' end,jsonb_build_object('tab','calendar','date',v_tomorrow::text),'calendar_tomorrow:'||v_today::text||':'||r.id) on conflict(dedupe_key) do nothing;
    end loop;
  end if;
end $$;

create or replace function public.yeorin_push_dispatch_ping() returns void language plpgsql security definer set search_path=public,extensions as $$
declare v_secret text;
begin
  select value into v_secret from public.push_private_config where key='cron_secret';if coalesce(v_secret,'')='' then return; end if;
  perform net.http_post(url:='https://putqauaiboychaalgyew.supabase.co/functions/v1/yeorin-push',headers:=jsonb_build_object('Content-Type','application/json','x-yeorin-cron',v_secret),body:='{"action":"dispatch"}'::jsonb,timeout_milliseconds:=15000);
end $$;

